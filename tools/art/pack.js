/* Packs art/out/*.png into src/sprites.js as data URIs.
   The game ships as one self-contained HTML file -- the Artifact and the Drop
   build both depend on that -- so there is nowhere to fetch an atlas from. Every
   sprite byte has to live inside the page.

     node tools/art/pack.js tick [more...]
*/
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', '..');
const OUT = path.join(root, 'art', 'out');
const ids = process.argv.slice(2);
if (!ids.length) { console.error('usage: node tools/art/pack.js <id> [id...]'); process.exit(1); }

let body = '', bytes = 0;
for (const id of ids) {
  const png = fs.readFileSync(path.join(OUT, id + '.png'));
  const man = JSON.parse(fs.readFileSync(path.join(OUT, id + '.json'), 'utf8'));
  const uri = 'data:image/png;base64,' + png.toString('base64');
  bytes += uri.length;
  body += ' ' + JSON.stringify(id) + ':{m:' + JSON.stringify(man) + ',u:' + JSON.stringify(uri) + '},\n';
}
const src = `/* Generated by tools/art/pack.js -- do not edit.
   Pre-rendered sprite atlases, inlined because the game is one file.
   Each entry: m = manifest (cell size, direction count, animation rows), u = png data URI. */
const SPRITES={
${body}};
`;
fs.writeFileSync(path.join(root, 'src', 'sprites.js'), src);
console.log('src/sprites.js: ' + ids.join(', ') + '  ' + (fs.statSync(path.join(root,'src','sprites.js')).size / 1024).toFixed(1) + 'KB');
