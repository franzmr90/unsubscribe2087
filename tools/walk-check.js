/* Click-check for the walkthrough decks.
   node tools/walk-check.js [outdir]
   Loads dist/unsubscribe.html under setContent. */
const {chromium}=require('playwright');
const fs=require('fs');
const path=require('path');
const OUT=process.argv[2];
const fail=m=>{console.error(m);process.exitCode=1;throw new Error(m)};
(async()=>{
const b=await chromium.launch();
const p=await b.newPage({viewport:{width:390,height:844}});
const errs=[];p.on('pageerror',e=>errs.push(e.stack||String(e)));
const root=path.join(__dirname,'..');
await p.setContent('<!doctype html><html><head><meta charset=utf-8></head><body style="margin:0">'+fs.readFileSync(path.join(root,'dist/unsubscribe.html'),'utf8')+'</body></html>');
await p.waitForTimeout(400);
await p.evaluate(()=>__g.skipDisc());
await p.waitForTimeout(200);
const lens=await p.evaluate(()=>({b:__g.WALK.basics.length,a:__g.WALK.advanced.length,arts:[...new Set(__g.WALK.basics.concat(__g.WALK.advanced).map(s=>s.art))]}));
if(lens.b<8||lens.a<8)fail('short deck '+JSON.stringify(lens));
const has=await p.evaluate(()=>!!document.getElementById('bWalk'));
if(!has)fail('no title button');
await p.evaluate(()=>document.getElementById('bWalk').scrollIntoView({block:'center'}));
await p.waitForTimeout(100);
if(OUT)await p.screenshot({path:path.join(OUT,'walk-title.png')});
await p.click('#bWalk');
await p.waitForFunction(()=>!document.getElementById('dlg').hidden&&document.getElementById('dT').textContent==='Walkthrough');
const chooser=await p.evaluate(()=>[...document.querySelectorAll('#dBtns button')].map(b=>b.textContent));
if(chooser.join('|')!=='Basics|Advanced|Close')fail('chooser '+chooser.join('|'));
await p.evaluate(()=>[...document.querySelectorAll('#dBtns button')].find(b=>b.textContent==='Basics').click());
await p.waitForFunction(()=>!document.getElementById('scene').hidden);
let st=await p.evaluate(()=>__g.walkState());
if(!st||st.i!==0||st.backOn||st.next!=='Next'||st.title!=='Your hands'||st.prev!=='title'||st.mode!=='scene')fail('basics open '+JSON.stringify(st));
if(await p.evaluate(()=>!document.getElementById('title').hidden))fail('title still showing over the deck');
await p.evaluate(()=>__g.fillSlide());
await p.waitForFunction(()=>!document.getElementById('scNext').disabled);
if(OUT)await p.screenshot({path:path.join(OUT,'walk-basics.png')});
await p.keyboard.press('ArrowRight');
st=await p.evaluate(()=>__g.walkState());
if(!st||st.i!==1||!st.backOn)fail('arrow advance '+JSON.stringify(st));
await p.click('#scBack');
st=await p.evaluate(()=>__g.walkState());
if(!st||st.i!==0||st.backOn)fail('back '+JSON.stringify(st));
for(let i=0;i<lens.b-1;i++){
  await p.evaluate(()=>__g.fillSlide());
  await p.waitForFunction(()=>!document.getElementById('scNext').disabled);
  await p.click('#scNext');
}
st=await p.evaluate(()=>__g.walkState());
if(!st||st.next!=='Done'||st.i!==lens.b-1)fail('done label '+JSON.stringify(st));
await p.evaluate(()=>__g.fillSlide());
await p.waitForFunction(()=>!document.getElementById('scNext').disabled);
await p.click('#scNext');
await p.waitForFunction(()=>document.getElementById('scene').hidden);
const backTitle=await p.evaluate(()=>({mode:__g.mode,title:document.getElementById('title').hidden,hud:document.getElementById('hud').hidden}));
if(backTitle.mode!=='title'||backTitle.title||!backTitle.hud)fail('return to title '+JSON.stringify(backTitle));
await p.click('#bWalk');
await p.waitForFunction(()=>!document.getElementById('dlg').hidden);
await p.evaluate(()=>[...document.querySelectorAll('#dBtns button')].find(b=>b.textContent==='Advanced').click());
await p.waitForFunction(()=>!document.getElementById('scene').hidden&&__g.walkState()&&__g.walkState().title==='The rig');
st=await p.evaluate(()=>__g.walkState());
if(!st||st.title!=='The rig'||st.backOn||st.prev!=='title')fail('advanced open '+JSON.stringify(st));
await p.evaluate(()=>__g.fillSlide());
await p.waitForFunction(()=>!document.getElementById('scNext').disabled);
if(OUT)await p.screenshot({path:path.join(OUT,'walk-advanced.png')});
await p.click('#scSkip');
await p.waitForFunction(()=>document.getElementById('scene').hidden&&__g.mode==='title');
const sk=async()=>{await p.evaluate(()=>{const s=document.getElementById('scene');if(s&&!s.hidden)document.getElementById('scSkip').click();const d=document.getElementById('dlg');if(d&&!d.hidden){const x=d.querySelector('#dBtns button:not([disabled])');x&&x.click()}})};
await p.evaluate(()=>{document.getElementById('title').hidden=true;__g.newGame('scrapper')});
for(let i=0;i<8;i++){await sk();await p.waitForTimeout(80)}
const pre=await p.evaluate(()=>({mode:__g.mode,zi:__g.W&&__g.W.zi,pre:__g.W&&__g.W.z&&__g.W.z.pre,title:document.getElementById('dT').textContent,open:!document.getElementById('dlg').hidden}));
if(pre.title==='Before you go')fail('prompted in the prequel '+JSON.stringify(pre));
await p.evaluate(()=>__g.openSheet('opts',{}));
await p.waitForTimeout(150);
const guide=await p.evaluate(()=>!!document.querySelector('[data-walk]'));
if(!guide)fail('options has no walkthrough');
await p.click('[data-walk]');
await p.waitForFunction(()=>!document.getElementById('dlg').hidden&&document.getElementById('dT').textContent==='Walkthrough');
await p.evaluate(()=>[...document.querySelectorAll('#dBtns button')].find(b=>b.textContent==='Close').click());
await p.waitForTimeout(80);
const closed=await p.evaluate(()=>({mode:__g.mode,sheet:document.getElementById('sheet').hidden,dlg:document.getElementById('dlg').hidden}));
if(closed.mode!=='play'||!closed.sheet||!closed.dlg)fail('options close '+JSON.stringify(closed));
await p.evaluate(()=>__g.playScene([{art:'wanderer',title:'END OF ACT I',text:'A story slide.'}]));
st=await p.evaluate(()=>__g.walkState());
if(!st||st.next!=='Begin'||st.backOn||st.back)fail('story button '+JSON.stringify(st));
await p.click('#scSkip');
await p.waitForFunction(()=>__g.mode==='play'&&document.getElementById('scene').hidden);
await p.evaluate(()=>{const G=__g.G;G.pre=2;G.seenIntro=true;G.q.q1=1;G.walkNew=1;__g.OPT.noWalk=false;__g.enter(0)});
await p.waitForFunction(()=>!document.getElementById('dlg').hidden&&document.getElementById('dT').textContent==='Before you go',{timeout:3000});
const box=await p.evaluate(()=>!!document.getElementById('noWalk'));
if(!box)fail('no checkbox');
await p.check('#noWalk');
await p.evaluate(()=>[...document.querySelectorAll('#dBtns button')].find(b=>b.textContent==='Not now').click());
await p.waitForTimeout(100);
let flag=await p.evaluate(()=>({no:__g.OPT.noWalk,nw:__g.G.walkNew,mode:__g.mode}));
if(!flag.no||flag.nw||flag.mode!=='play')fail('checkbox '+JSON.stringify(flag));
await p.evaluate(()=>{__g.G.walkNew=1;__g.enter(0)});
await p.waitForTimeout(900);
let again=await p.evaluate(()=>({open:!document.getElementById('dlg').hidden,t:document.getElementById('dT').textContent,nw:__g.G.walkNew}));
if(again.open&&again.t==='Before you go')fail('asked again after the checkbox '+JSON.stringify(again));
await p.evaluate(()=>{__g.OPT.noWalk=false;__g.G.walkNew=0;__g.enter(0)});
await p.waitForTimeout(900);
again=await p.evaluate(()=>({open:!document.getElementById('dlg').hidden,t:document.getElementById('dT').textContent}));
if(again.open&&again.t==='Before you go')fail('veteran nagged '+JSON.stringify(again));
await p.evaluate(()=>{__g.G.walkNew=1;__g.enter(0)});
await p.waitForFunction(()=>{const d=document.getElementById('dlg'),c=document.getElementById('noWalk');return d&&!d.hidden&&document.getElementById('dT').textContent==='Before you go'&&c&&!c.checked},{timeout:3000});
await p.evaluate(()=>[...document.querySelectorAll('#dBtns button')].find(b=>b.textContent==='Not now').click());
flag=await p.evaluate(()=>({no:__g.OPT.noWalk,nw:__g.G.walkNew}));
if(flag.no||flag.nw)fail('dismiss without the box '+JSON.stringify(flag));
await p.evaluate(()=>{__g.G.walkNew=1;__g.enter(0)});
await p.waitForFunction(()=>{const d=document.getElementById('dlg'),c=document.getElementById('noWalk');return d&&!d.hidden&&document.getElementById('dT').textContent==='Before you go'&&c&&!c.checked},{timeout:3000});
await p.evaluate(()=>[...document.querySelectorAll('#dBtns button')].find(b=>b.textContent==='Basics').click());
await p.waitForFunction(()=>!document.getElementById('scene').hidden&&__g.walkState()&&__g.walkState().prev==='play');
await p.click('#scSkip');
await p.waitForFunction(()=>__g.mode==='play'&&document.getElementById('scene').hidden);
if(errs.length)fail('page errors\n'+errs.join('\n'));
console.log('walkthrough ok',lens.b,lens.a);
await b.close();
process.exit(process.exitCode||0);
})().catch(e=>{console.error(e);process.exit(1)});
