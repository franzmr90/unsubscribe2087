#!/usr/bin/env node
/* Bakes the design tables in data/ into JavaScript the game and the server share.

   This is Diablo 2's arrangement: designers edit tab-separated sheets (D2 had
   monstats.txt, skills.txt and the rest), and the build compiles them. The game
   page and the server both read the compiled file, so a monster added to the
   sheet reaches both at once instead of needing a second hand-kept copy.

   data/monstats.tsv -> src/monstats.js   (ET, ETY, RES, BOSSES)
   data/treasure.tsv -> src/treasure.js   (TC: what a kill or a box drops)
   data/levels.tsv   -> src/levels.js     (ZONES, HUB_TOWNS; D2's levels.txt)
   data/itemtypes.tsv, affixes.tsv, uniques.tsv, sets.tsv -> src/items.js (BASE, AFX, AFX2, UNI, SETS)
   data/classes.tsv, skills.tsv -> src/skills.js (CLS: classes and their skill trees)

   One row per monster. Blank cells mean "not set". Columns:
     id        key used everywhere in code (max 16 characters, the server's limit)
     name      what the player reads
     body      which drawing it borrows (blank = its own, by id)
     hp dmg spd r range xp atk sight   the stat card
     ranged slow                       1 = yes
     drain sil flee                    numbers, blank = none
     col1 col2                         palette
     deals     damage type it hits with (blank = impact)
     boss      1 = a boss: the server expects 2.5x life
     res_*     multiplier taken from that damage type (0 = immune, blank = 1)

   Run by build.sh. `node tools/data/bake.js --check` exits 1 when src/ is stale. */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', '..');
const RESK = ['impact', 'surge', 'rust', 'heat', 'noise'];
const DEALS = new Set(RESK);

function readTsv(file) {
  const text = fs.readFileSync(file, 'utf8').replace(/\r/g, '');
  const lines = text.split('\n').filter(l => l.trim() && !l.startsWith('#'));
  const head = lines.shift().split('\t');
  return lines.map((l, i) => {
    const cells = l.split('\t');
    if (cells.length > head.length) throw new Error(`${path.basename(file)} row ${i + 2}: ${cells.length} cells, header has ${head.length}`);
    const o = {};
    head.forEach((h, j) => { o[h] = (cells[j] || '').trim(); });
    o._row = i + 2;
    return o;
  });
}

function num(row, col, file) {
  const v = row[col];
  if (v === '') return undefined;
  const n = Number(v);
  if (!Number.isFinite(n)) throw new Error(`${file} row ${row._row} (${row.id}): ${col} is "${v}", not a number`);
  return n;
}

let KINDS = null; /* the monster ids, for sheets that name monsters */
function monstats() {
  const file = 'data/monstats.tsv';
  const rows = readTsv(path.join(root, file));
  const ET = {}, ETY = {}, RES = {}, BOSSES = {};
  for (const r of rows) {
    const k = r.id;
    if (!/^[a-z][a-z0-9_]{0,15}$/.test(k)) throw new Error(`${file} row ${r._row}: id "${k}" must be lowercase, at most 16 characters`);
    if (ET[k]) throw new Error(`${file} row ${r._row}: id "${k}" appears twice`);
    if (!r.name) throw new Error(`${file} row ${r._row} (${k}): no name`);
    const e = { n: r.name };
    if (r.body) e.spr = r.body;
    for (const c of ['hp', 'dmg', 'spd', 'r', 'range', 'xp', 'atk', 'sight']) {
      const v = num(r, c, file);
      if (v === undefined) throw new Error(`${file} row ${r._row} (${k}): ${c} is blank`);
      e[c] = v;
    }
    for (const c of ['ranged', 'slow']) if (r[c] !== '' && r[c] !== '0') e[c] = true;
    for (const c of ['drain', 'sil', 'flee']) { const v = num(r, c, file); if (v !== undefined) e[c] = v; }
    e.pal = [r.col1, r.col2];
    ET[k] = e;
    if (r.deals) {
      if (!DEALS.has(r.deals)) throw new Error(`${file} row ${r._row} (${k}): deals "${r.deals}" is not one of ${RESK.join(', ')}`);
      ETY[k] = r.deals;
    }
    const res = {};
    for (const t of RESK) { const v = num(r, 'res_' + t, file); if (v !== undefined) res[t] = v; }
    if (Object.keys(res).length) RES[k] = res;
    if (r.boss === '1') BOSSES[k] = 1;
  }
  for (const k in ET) if (ET[k].spr && !ET[ET[k].spr] && !['boss', 'mono'].includes(ET[k].spr))
    throw new Error(`${file} (${k}): body "${ET[k].spr}" is not a monster id`);
  KINDS = ET;
  const j = o => JSON.stringify(o);
  return `/* Generated by tools/data/bake.js from data/monstats.tsv -- edit the sheet, not this file. */
const ET=${j(ET)};
const ETY=${j(ETY)};
const RES=${j(RES)};
const BOSSES=${j(BOSSES)};
if (typeof module !== 'undefined' && module.exports) module.exports = { ET, ETY, RES, BOSSES };
`;
}

function treasure() {
  const file = 'data/treasure.tsv';
  const rows = readTsv(path.join(root, file));
  const byId = {};
  for (const r of rows) {
    if (byId[r.id]) throw new Error(`${file} row ${r._row}: id "${r.id}" appears twice`);
    byId[r.id] = r;
  }
  /* A row with `like` takes every blank cell from that row, the way D2's
     treasure classes could stand on another. Its own name always wins. */
  const cell = (r, c, seen = new Set()) => {
    if (r[c] !== '' || !r.like) return r[c];
    if (seen.has(r.id)) throw new Error(`${file}: rows ${[...seen].join(' -> ')} are like each other in a loop`);
    seen.add(r.id);
    const base = byId[r.like];
    if (!base) throw new Error(`${file} row ${r._row} (${r.id}): like "${r.like}" is not a row`);
    return cell(base, c, seen);
  };
  const n = (r, c, need) => {
    const v = cell(r, c);
    if (v === '') { if (need) throw new Error(`${file} row ${r._row} (${r.id}): ${c} is blank`); return undefined; }
    const x = Number(v);
    if (!Number.isFinite(x)) throw new Error(`${file} row ${r._row} (${r.id}): ${c} is "${v}", not a number`);
    return x;
  };
  const TC = {};
  for (const r of rows) {
    const t = { n: r.name, picks: n(r, 'picks', 1), no: n(r, 'none', 1), gold: n(r, 'credits', 1), item: n(r, 'item', 1), stim: n(r, 'stim', 1),
      q: { u: n(r, 'unique_1in', 1), s: n(r, 'set_1in', 1), r: n(r, 'rare_1in', 1), m: n(r, 'magic_1in', 1) } };
    const gm = n(r, 'credit_mul'), jw = n(r, 'jewel_mul'), note = cell(r, 'note');
    if (gm !== undefined) t.goldMul = gm;
    if (note) t.note = note;
    if (jw !== undefined) t.jewel = jw;
    TC[r.id] = t;
  }
  return `/* Generated by tools/data/bake.js from data/treasure.tsv -- edit the sheet, not this file. */
const TC=${JSON.stringify(TC)};
if (typeof module !== 'undefined' && module.exports) module.exports = { TC };
`;
}

function levels() {
  const file = 'data/levels.tsv';
  const rows = readTsv(path.join(root, file));
  const ZONES = [];
  const kind = (r, k, col) => {
    if (k && !KINDS[k]) throw new Error(`${file} row ${r._row} (${r.name}): ${col} "${k}" is not in data/monstats.tsv`);
    return k;
  };
  const num = (r, c) => {
    if (r[c] === '') return undefined;
    const x = Number(r[c]);
    if (!Number.isFinite(x)) throw new Error(`${file} row ${r._row} (${r.name}): ${c} is "${r[c]}", not a number`);
    return x;
  };
  rows.forEach((r, i) => {
    if (Number(r.id) !== i) throw new Error(`${file} row ${r._row}: id ${r.id} out of order; zone ids are positions and must run 0, 1, 2 ...`);
    const z = { n: r.name };
    const flag = c => r[c] !== '' && r[c] !== '0';
    if (flag('town')) z.town = true;
    if (r.act) z.act = num(r, 'act');
    if (r.lvl) z.lvl = num(r, 'lvl');
    z.style = r.style;
    z.amb = num(r, 'amb');
    if (flag('boss')) z.boss = true;
    if (r.boss_kind) z.bossK = kind(r, r.boss_kind, 'boss_kind');
    if (r.guard) z.guard = kind(r, r.guard, 'guard');
    if (r.boss_quest) z.bq = r.boss_quest;
    if (r.mix) z.mix = r.mix.split(/\s+/).map(m => {
      const [k, w] = m.split(':');
      if (!(Number(w) > 0)) throw new Error(`${file} row ${r._row} (${r.name}): mix "${m}" should be kind:weight`);
      return [kind(r, k, 'mix'), Number(w)];
    });
    if (r.su_kind) z.su = { k: kind(r, r.su_kind, 'su_kind'), n: r.su_name, mods: r.su_mods ? r.su_mods.split(/\s+/) : [], q: r.su_quest || null };
    if (r.intro) z.intro = r.intro;
    if (r.out) z.out = num(r, 'out');
    if (flag('sim')) z.sim = true;
    if (flag('sub')) z.sub = true;
    if (flag('secret')) z.secret = true;
    if (r.pre) z.pre = num(r, 'pre');
    if (z.amb === undefined) throw new Error(`${file} row ${r._row} (${r.name}): amb is blank`);
    ZONES.push(z);
  });
  /* The server keeps players safe and regenerating in an act's hub town. */
  const TOWNS = ZONES.map((z, i) => z.town && z.act ? i : -1).filter(i => i >= 0);
  return `/* Generated by tools/data/bake.js from data/levels.tsv -- edit the sheet, not this file.
   Zone ids are row positions. Some zones are changed in play (the subpoena zone takes the
   look of the zone it was served in), so code that needs the sheet's values reads them early. */
const ZONES=${JSON.stringify(ZONES)};
const HUB_TOWNS=${JSON.stringify(TOWNS)};
if (typeof module !== 'undefined' && module.exports) module.exports = { ZONES, HUB_TOWNS };
`;
}

/* Items: D2 kept these as weapons/armor.txt, magicprefix/suffix.txt, uniqueitems.txt
   and setitems.txt. Here they are four sheets baked into one file. */
function items() {
  const SLOTS = ['weapon', 'helm', 'armor', 'gloves', 'boots', 'belt', 'ring', 'amulet'];
  const numOr = (file, r, c) => {
    if (r[c] === '') return undefined;
    const x = Number(r[c]);
    if (!Number.isFinite(x)) throw new Error(`${file} row ${r._row}: ${c} is "${r[c]}", not a number`);
    return x;
  };
  const need = (file, r, c) => { const x = numOr(file, r, c); if (x === undefined) throw new Error(`${file} row ${r._row}: ${c} is blank`); return x; };
  const slot = (file, r, s) => { if (!SLOTS.includes(s)) throw new Error(`${file} row ${r._row}: slot "${s}" is not one of ${SLOTS.join(', ')}`); return s; };
  /* mods are written stat=min/max, separated by spaces */
  const mods = (file, r) => {
    const o = {};
    for (const m of r.mods.split(/\s+/).filter(Boolean)) {
      const hit = /^([A-Za-z_]+)=(-?[\d.]+)\/(-?[\d.]+)$/.exec(m);
      if (!hit) throw new Error(`${file} row ${r._row}: mod "${m}" should look like hp=40/60`);
      o[hit[1]] = [Number(hit[2]), Number(hit[3])];
    }
    return o;
  };

  let file = 'data/itemtypes.tsv';
  const BASE = {};
  for (const r of readTsv(path.join(root, file))) {
    const tiers = BASE[slot(file, r, r.slot)] || (BASE[r.slot] = []);
    const t = need(file, r, 'tier');
    if (t > tiers.length) throw new Error(`${file} row ${r._row}: tier ${t} skips a tier`);
    const b = { n: r.name };
    const dm = numOr(file, r, 'dmg'), sp = numOr(file, r, 'speed');
    if (dm !== undefined) b.d = dm;
    if (sp !== undefined) b.s = sp;
    (tiers[t] || (tiers[t] = [])).push(b);
  }
  /* A unique's base is the name it shows, and class weapons (p10 FAM) have bases of their own, so it is not checked. */
  const base = (f, r) => { if (!r.base) throw new Error(`${f} row ${r._row}: base is blank`); return r.base; };

  file = 'data/affixes.tsv';
  const AFX = [], AFX2 = [];
  let cur = null;
  for (const r of readTsv(path.join(root, file))) {
    if (r.list) {
      if (r.list !== 'AFX' && r.list !== 'AFX2') throw new Error(`${file} row ${r._row}: list is "${r.list}", not AFX or AFX2`);
      cur = { k: r.stat };
      const pre = numOr(file, r, 'prefix');
      if (pre !== undefined) cur.pre = pre;
      cur.t = r.text;
      if (r.slots) cur.sl = r.slots.split(/\s+/).map(s => slot(file, r, s));
      const w = numOr(file, r, 'weight');
      if (w !== undefined) cur.w = w;
      if (r.group) cur.grp = r.group;
      cur.tiers = [];
      (r.list === 'AFX' ? AFX : AFX2).push(cur);
    } else if (!cur) throw new Error(`${file} row ${r._row}: a tier row before any affix`);
    cur.tiers.push([r.tier_name, need(file, r, 'tier_level'), need(file, r, 'min'), need(file, r, 'max')]);
  }

  file = 'data/uniques.tsv';
  const UNI = [], ids = new Set();
  for (const r of readTsv(path.join(root, file))) {
    if (ids.has(r.id)) throw new Error(`${file} row ${r._row}: id "${r.id}" appears twice`);
    ids.add(r.id);
    const u = { id: r.id };
    if (r.class) u.cls = r.class;
    Object.assign(u, { n: r.name, slot: slot(file, r, r.slot), il: need(file, r, 'ilvl'), base: base(file, r) });
    for (const [c, k] of [['ind', 'ind'], ['bi', 'bi'], ['patch', 'patch'], ['boss_only', 'bossOnly'], ['isk', 'isk']]) {
      const x = numOr(file, r, c);
      if (x !== undefined) u[k] = x;
    }
    if (r.drops) u.tc = r.drops;
    if (r.per_level) {
      u.per = {};
      for (const m of r.per_level.split(/\s+/)) { const [k, x] = m.split('='); u.per[k] = Number(x); }
    }
    if (r.grant) u.grant = r.grant.split(/\s+/).map(Number);
    u.mods = mods(file, r);
    u.sp = r.special || null; /* blank: no special property */
    u.fl = r.flavor;
    UNI.push(u);
  }

  file = 'data/sets.tsv';
  const SETS = {};
  let set = null;
  for (const r of readTsv(path.join(root, file))) {
    if (r.set) set = SETS[r.set] = { n: r.set_name, b2: r.bonus2, b3: r.bonus3, items: [] };
    else if (!set) throw new Error(`${file} row ${r._row}: an item before any set`);
    const it = { id: r.id, n: r.name, slot: slot(file, r, r.slot), il: need(file, r, 'ilvl'), base: base(file, r) };
    const bi = numOr(file, r, 'bi');
    if (bi !== undefined) it.bi = bi;
    it.mods = mods(file, r);
    set.items.push(it);
  }

  const j = o => JSON.stringify(o);
  return `/* Generated by tools/data/bake.js from data/itemtypes.tsv, affixes.tsv, uniques.tsv and
   sets.tsv -- edit the sheets, not this file. */
const BASE=${j(BASE)};
const AFX=${j(AFX)};
const AFX2=${j(AFX2)};
const UNI=${j(UNI)};
const SETS=${j(SETS)};
if (typeof module !== 'undefined' && module.exports) module.exports = { BASE, AFX, AFX2, UNI, SETS };
`;
}

/* ---------- classes and skills (D2's charstats.txt, skills.txt, skilldesc.txt) ----------
   data/classes.tsv, one row per class, in select-screen order:
     id name tag good weak build   the text on the select screen
     melee (1/0) mult interval speed colour locked
     Life stays in src/formulas.js (FORMULAS.cls), because the server reads it there.
   data/skills.tsv, one row per skill, in tree order. Saves keep skills by position, so a
   class must have exactly 15 rows and moving a row moves a save's points.
     class row name button (\n = line break) kind (active, passive, aura) cost cd
     calc   named formulas in the rank L, "dmg=pct(1.3+.15*L); chance=15+2*L"
     desc   the tooltip; {name} shows that formula's value at the current rank
   A formula may use numbers, + - * / ( ), comparisons, a ? b : c, 'quoted text', L, the
   names before it on the row, the functions below, and the game values below. Nothing else. */
const SK_FN = { pct: 'pct', min: 'Math.min', max: 'Math.max', floor: 'Math.floor', round: 'Math.round' };
const SK_FIX = { fixed1: 1, fixed2: 2 };
const SK_GV = {
  cpi: '(G&&G.cpi||1)',
  schema: "(G&&G.schema?': '+DTY[G.schema].n:'')",
  ward_sec: 'FORMULAS.brace.ward.sec', ward_pct: 'FORMULAS.brace.ward.pct',
  cipher_cap: 'FORMULAS.brace.cipher.cap', cipher_per: 'FORMULAS.brace.cipher.per'
};
function skFormula(src, names, where) {
  const toks = [];
  const re = /\s*(?:(\d*\.?\d+)|([A-Za-z_]\w*)|('[^'\\]*')|(>=|<=|===|==|!=|[-+*/()?:<>,]))/y;
  let m;
  re.lastIndex = 0;
  while (re.lastIndex < src.length) {
    const at = re.lastIndex;
    if (!(m = re.exec(src))) { if (/^\s*$/.test(src.slice(at))) break; throw new Error(`${where}: cannot read "${src.slice(at)}"`); }
    toks.push(m[1] ? { n: m[1] } : m[2] ? { id: m[2] } : m[3] ? { s: m[3] } : { op: m[4] });
  }
  let k = 0;
  function expr(stop) {
    let o = '';
    while (k < toks.length) {
      const t = toks[k];
      if (t.op && stop.includes(t.op)) return o;
      k++;
      if (t.n || t.s) o += t.n || t.s;
      else if (t.op === '(') { o += '(' + expr([')']) + ')'; k++; }
      else if (t.op === ',') o += ',';
      else if (t.op) o += t.op === '==' ? '===' : t.op;
      else if (t.id === 'L' || names.has(t.id)) o += t.id;
      else if (SK_GV[t.id]) o += SK_GV[t.id];
      else if (SK_FN[t.id] || SK_FIX[t.id]) {
        if (!toks[k] || toks[k].op !== '(') throw new Error(`${where}: ${t.id} needs (...)`);
        k++;
        const inner = expr([')']); k++;
        o += SK_FIX[t.id] ? '(' + inner + ').toFixed(' + SK_FIX[t.id] + ')' : SK_FN[t.id] + '(' + inner + ')';
      } else throw new Error(`${where}: "${t.id}" is not L, a name before it on the row, a function or a game value`);
    }
    if (stop.length && stop[0] === ')') throw new Error(`${where}: a ( is not closed`);
    return o;
  }
  const out = expr([]);
  return out;
}
function skills() {
  const unesc = s => s.replace(/\\n/g, '\n');
  let file = 'data/classes.tsv';
  const CLS = {};
  for (const r of readTsv(path.join(root, file))) {
    if (!/^[a-z]+$/.test(r.id)) throw new Error(`${file} row ${r._row}: id "${r.id}"`);
    const o = { n: r.name, tag: r.tag, good: r.good, weak: r.weak, bld: r.build, melee: r.melee === '1' };
    for (const [k, c] of [['mult', 'mult'], ['ivl', 'interval'], ['spd', 'speed']]) o[k] = num(r, c, file);
    o.col = r.colour;
    if (r.locked) o.locked = r.locked;
    o.sk = [];
    CLS[r.id] = o;
  }
  file = 'data/skills.tsv';
  for (const r of readTsv(path.join(root, file))) {
    const where = `${file} row ${r._row} (${r.name})`;
    const c = CLS[r.class];
    if (!c) throw new Error(`${where}: no class "${r.class}" in data/classes.tsv`);
    if (Number(r.row) !== c.sk.length + 1) throw new Error(`${where}: row ${r.row}, expected ${c.sk.length + 1}`);
    if (!['active', 'passive', 'aura'].includes(r.kind)) throw new Error(`${where}: kind "${r.kind}"`);
    const s = { n: r.name, ab: unesc(r.button), a: r.kind === 'passive' ? 0 : 1 };
    if (r.kind === 'aura') s.aura = 1;
    for (const k of ['cost', 'cd']) { const v = num(r, k, file); if (v !== undefined) s[k] = v; }
    s.dt = r.desc;
    const names = new Set(), parts = [];
    for (const piece of r.calc.split(';').map(x => x.trim()).filter(Boolean)) {
      const eq = piece.indexOf('=');
      const name = piece.slice(0, eq).trim();
      if (eq < 1 || !/^[a-z_][a-z0-9_]*$/i.test(name) || name === 'L' || SK_GV[name] || SK_FN[name] || SK_FIX[name]) throw new Error(`${where}: "${piece}" should be name=formula`);
      if (names.has(name)) throw new Error(`${where}: ${name} twice`);
      parts.push(name + '=' + skFormula(piece.slice(eq + 1), names, where + ' ' + name));
      names.add(name);
    }
    const used = new Set();
    r.desc.replace(/\{(\w+)\}/g, (m, k) => { if (!names.has(k)) throw new Error(`${where}: the desc has {${k}} and the calc has no ${k}`); used.add(k); });
    for (const k of names) if (!used.has(k)) throw new Error(`${where}: ${k} is worked out and never shown`);
    s.dv = parts.length ? `L=>{const ${parts.join(',')};return{${[...names].join(',')}}}` : null;
    c.sk.push(s);
  }
  const j = JSON.stringify;
  const lines = Object.entries(CLS).map(([id, c]) => {
    if (c.sk.length !== 15) throw new Error(`data/skills.tsv: ${id} has ${c.sk.length} skills, not 15`);
    const head = Object.entries(c).filter(([k]) => k !== 'sk').map(([k, v]) => k + ':' + j(v));
    head.splice(5, 0, `hp:FORMULAS.cls.${id}.hp`, `hpL:FORMULAS.cls.${id}.hpL`);
    const sk = c.sk.map(s => ' {' + Object.entries(s).map(([k, v]) => k + ':' + (k === 'dv' ? v : j(v))).join(',') + '}');
    return ` ${id}:{${head.join(',')},sk:[\n${sk.join(',\n')}]}`;
  });
  return `/* Generated by tools/data/bake.js from data/classes.tsv and data/skills.tsv -- edit the
   sheets, not this file. dt is the tooltip with {holes}; dv works out the holes at a rank. */
const CLS={
${lines.join(',\n')}
};
for(const c in CLS)for(const s of CLS[c].sk){const t=s.dt,v=s.dv;s.d=L=>{const o=v?v(L):{};return t.replace(/\\{(\\w+)\\}/g,(m,k)=>k in o?o[k]:m)}}
if (typeof module !== 'undefined' && module.exports) module.exports = { CLS };
`;
}

const out = { 'src/monstats.js': monstats(), 'src/treasure.js': treasure(), 'src/levels.js': levels(), 'src/items.js': items(), 'src/skills.js': skills() };
