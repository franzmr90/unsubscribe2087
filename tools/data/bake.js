for (const [rel, text] of Object.entries(out)) {
  const p = path.join(root, rel);
  const was = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : '';
  if (was === text) continue;
  if (check) { console.error(`${rel} is stale: run node tools/data/bake.js`); stale = 1; }
  else fs.writeFileSync(p, text);
}
process.exit(stale);
